const DICTS: Record<Locale, Record<I18nKey, string>> = { tr, en };

export function translate(locale: Locale, key: I18nKey, params?: Record<string, string | number>): string {
  let s = DICTS[locale][key] ?? DICTS.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function errorText(locale: Locale, code: string | undefined): string {
  const key = `err_${code}` as I18nKey;
  return key in tr ? translate(locale, key) : translate(locale, 'err_generic');
}

const I18nContext = createContext<{ locale: Locale; t: (k: I18nKey, p?: Record<string, string | number>) => string }>({
  locale: 'tr',
  t: (k, p) => translate('tr', k, p),
});

export function I18nProvider({ locale, children }: { locale: Locale; children: React.ReactNode }) {
  const value = useMemo(() => ({ locale, t: (k: I18nKey, p?: Record<string, string | number>) => translate(locale, k, p) }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
